import { createRequire } from "node:module";
const require = createRequire("/home/user/pgtooling/");
const puppeteer = require("puppeteer-core");
const BASE = process.env.BASE_URL || "http://localhost:3000";
const browser = await puppeteer.launch({ executablePath: "/tmp/al2023/chromium", headless: "new", args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const page = await browser.newPage();
await page.setViewport({ width: 430, height: 932, isMobile: true, hasTouch: true });
page.on("dialog", (d) => d.accept());
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.goto(`${BASE}/order?biz=1`, { waitUntil: "networkidle0", timeout: 60000 });
await page.waitForSelector('[data-testid^="oo-add-"]', { timeout: 30000 });
const firstAdd = await page.evaluate(() => document.querySelector('[data-testid^="oo-add-"]').getAttribute("data-testid"));
console.log("add:", firstAdd);
await page.click(`[data-testid="${firstAdd}"]`);
await page.waitForSelector('[data-testid="oo-cart"]', { timeout: 10000 });
await page.type('[data-testid="oo-name"]', "Diag Place");
await page.type('[data-testid="oo-phone"]', "0551444555");
const centreClick = async (tid) => { await page.$eval(`[data-testid="${tid}"]`, (el) => el.scrollIntoView({ block: "center" })); await sleep(150); await page.click(`[data-testid="${tid}"]`); };
await centreClick("oo-delivery");
await page.waitForSelector('[data-testid="oo-dest-input"]', { timeout: 5000 });
await page.type('[data-testid="oo-dest-input"]', "Diag Kasoa toll booth");
await page.waitForSelector('[data-testid="oo-pin-root"]', { timeout: 10000 });
// exact coordinates far from the shop (order-page-regression's values)
await centreClick("oo-pin-manual-toggle");
await page.waitForSelector('[data-testid="oo-pin-manual-lat"]', { timeout: 10000 });
const setInput = async (sel, val) => page.evaluate((s, v) => { const el = document.querySelector(s); const proto = HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto, "value").set.call(el, v); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, sel, val);
await setInput('[data-testid="oo-pin-manual-lat"]', "5.650123");
await setInput('[data-testid="oo-pin-manual-lng"]', "-0.155456");
await centreClick("oo-pin-manual-apply");
await sleep(900);
await centreClick("oo-place");
await sleep(4500);
const err = await page.$eval('[data-testid="oo-error"]', (el) => el.textContent).catch(() => null);
const code = await page.$eval('[data-testid="oo-code"]', (el) => el.textContent).catch(() => null);
const shopWarn = await page.$eval('[data-testid="oo-pin-shop-warn"]', (el) => el.textContent).catch(() => null);
console.log(JSON.stringify({ err, code, shopWarn }));
await page.screenshot({ path: "/home/user/gomina360_app_V1.1/dev-tooling/backups/diag-place.png" });
await browser.close();
